CREATE TABLE BANK_BRANCHES (
    branch_id   NUMBER PRIMARY KEY,
    branch_name VARCHAR2(50),
    city        VARCHAR2(30),
    state       VARCHAR2(30)
);

CREATE TABLE BANK_CUSTOMERS (
    customer_id      NUMBER PRIMARY KEY,
    first_name       VARCHAR2(30),
    last_name        VARCHAR2(30),
    gender           VARCHAR2(10),
    date_of_birth    DATE,
    city             VARCHAR2(30),
    registration_date DATE,
    email            VARCHAR2(100),
    phone            VARCHAR2(15)
);

CREATE TABLE BANK_ACCOUNTS (
    account_id    NUMBER PRIMARY KEY,
    customer_id   NUMBER,
    branch_id     NUMBER,
    account_type  VARCHAR2(25),
    opening_date  DATE,
    balance       NUMBER(12,2),
    account_status VARCHAR2(20)
);

CREATE TABLE BANK_TRANSACTIONS (
    transaction_id    NUMBER PRIMARY KEY,
    account_id        NUMBER,
    related_account_id NUMBER,
    transaction_date  DATE,
    transaction_type  VARCHAR2(25),
    amount            NUMBER(12,2),
    transaction_status VARCHAR2(20),
    channel           VARCHAR2(25)
);

CREATE TABLE BANK_LOANS (
    loan_id       NUMBER PRIMARY KEY,
    customer_id   NUMBER,
    loan_type     VARCHAR2(30),
    loan_amount   NUMBER(12,2),
    interest_rate NUMBER(5,2),
    loan_status   VARCHAR2(20),
    issue_date    DATE
);

CREATE TABLE BANK_CARDS (
    card_id     NUMBER PRIMARY KEY,
    customer_id NUMBER,
    account_id  NUMBER,
    card_type   VARCHAR2(15),
    issue_date  DATE,
    card_status VARCHAR2(15)
);

CREATE TABLE BANK_TRANSACTION_ALERTS (
    alert_id       NUMBER PRIMARY KEY,
    transaction_id NUMBER,
    alert_type     VARCHAR2(50),
    risk_score     NUMBER(5,2),
    review_status  VARCHAR2(25),
    alert_date     DATE
);




